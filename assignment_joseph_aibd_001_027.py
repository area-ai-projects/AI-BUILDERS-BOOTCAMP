# Original string
print(f"Original String: {String_var}")

# Uppercase
uppercase_string = String_var.upper()
print(f"Uppercase: {uppercase_string}")

# Lowercase
lowercase_string = String_var.lower()
print(f"Lowercase: {lowercase_string}")

# Slicing :From index 6 to 11 ( "World")
sliced_string = String_var[6:11]
print(f"Sliced String (index 6 to 11): {sliced_string}")

# Slicing: From the beginning to index 5 ("Hello")
sliced_string_start = String_var[:5]
print(f"Sliced String (beginning to index 5): {sliced_string_start}")

# Slicing: From index 6 to the end ("World !!!")
sliced_string_end = String_var[6:]
print(f"Sliced String (index 6 to end): {sliced_string_end}")

# String with leading and trailing whitespace
whitespace_string = "   Python Programming   "
