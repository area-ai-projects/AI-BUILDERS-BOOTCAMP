List_var = ["TensorFlow", "PyTorch", "Scikit-learn", "Keras", "Hugging Face"]

# Tuple variable
Tuple_var = (10, 20, 30, 40, 50)

# Dictionary variable
Dictionary_var = {"tool1": "TensorFlow", "tool2": "PyTorch", "version": 2.0}


print("String:" + String_var)
