# Data Types Practice

# String
student_name = "Opeyemi"

# Integer
age = 27

# Float
cgpa = 3.20

# Boolean
is_graduated = True

# List
ai_tools = ["ChatGPT", "Gemini", "Claude", "Copilot", "Perplexity"]

# Tuple
programming_languages = ("Python", "Java", "C++")

# Dictionary
student_info = {
    "name": "Opeyemi",
    "age": 27,
    "state": "Lagos"
}

# Print values and their types
print(student_name, type(student_name))
print(age, type(age))
print(cgpa, type(cgpa))
print(is_graduated, type(is_graduated))
print(ai_tools, type(ai_tools))
print(programming_languages, type(programming_languages))
print(student_info, type(student_info))